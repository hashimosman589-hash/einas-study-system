export function seedExamples() {
  const count = db.prepare('SELECT COUNT(*) c FROM lectures').get().c;
  if (count > 0) return { seeded: 0, reason: 'الجدول يحتوي محاضرات بالفعل' };

  const owner = db.prepare("SELECT id FROM users WHERE role = 'admin' ORDER BY id LIMIT 1").get();
  if (!owner) return { seeded: 0, reason: 'لا يوجد حساب مدير للربط' };

  const insLec = db.prepare(
    `INSERT INTO lectures (user_id, title, subject, file_name, file_path, file_type, content, status, progress, current_stage, updated_at)
     VALUES (?,?,?,?,?,?,?,'ready',100,'completed',datetime('now'))`
  );
  const insSum = db.prepare(
    `INSERT INTO summaries (lecture_id, user_id, summary, key_points, important_terms, review_topics)
     VALUES (?,?,?,?,?,?)`
  );
  const insQ = db.prepare(
    `INSERT INTO questions (lecture_id, user_id, text, type, options, correct_answer, explanation, topic, question_en, question_ar, answer_en, answer_ar, difficulty, page)
     VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)`
  );

  let seeded = 0;
  db.exec('BEGIN');
  try {
    for (const ex of EXAMPLES) {
      const info = insLec.run(
        owner.id, ex.title, ex.subject,
        `${ex.title}.txt`, `examples/${Date.now()}-${seeded}.txt`, ex.file_type,
        ex.content
      );
      const lectureId = Number(info.lastInsertRowid);
      insSum.run(
        lectureId, owner.id, ex.summary,
        JSON.stringify(ex.key_points),
        JSON.stringify(ex.important_terms),
        JSON.stringify(ex.review_topics)
      );
      for (const question of ex.questions) {
        insQ.run(
          lectureId, owner.id, question.text, question.type, question.options,
          question.correct_answer, question.explanation, question.topic,
          question.question_en, question.question_ar, question.answer_en, question.answer_ar,
          question.difficulty, question.page
        );
      }
      seeded++;
    }
    db.exec('COMMIT');
  } catch (e) {
    db.exec('ROLLBACK');
    throw e;
  }
  return { seeded, reason: seeded ? 'تمت إعادة إدخال الأمثلة (المحاضرات القديمة)' : 'لا شيء' };
}
